/**
 * Synthetic error-detection evaluation (implementation.md §7.3).
 * For every N5 kanji × injector × VARIANTS, inject a known mistake, add human-like noise,
 * analyse, and compute per-error-type precision / recall / F1.
 * Kanji are split into a tuning half and a held-out half; both are reported.
 *
 *   npm run evaluate            → prints tables, writes docs/evaluation/synthetic-results.md
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { analyze } from "../src/core/analyze.ts";
import { humanize, INJECT, rng, toAttempt } from "../src/core/synth/index.ts";
import type { ErrorType, KanjiData } from "../src/core/types.ts";

const VARIANTS = Number(process.env.VARIANTS ?? 20);
const data: KanjiData = JSON.parse(readFileSync("public/data/kanji.json", "utf8"));
const TYPES: ErrorType[] = ["order", "direction", "count", "proportion", "position", "confusion"];

type Sample = { char: string; expect: ErrorType | "clean"; got: Set<ErrorType>; ms: number };

function run(chars: string[], seed: number): Sample[] {
  const r = rng(seed);
  const out: Sample[] = [];
  for (const c of chars)
    for (const inject of Object.values(INJECT))
      for (let v = 0; v < VARIANTS; v++) {
        const inj = inject(data, c, r);
        if (!inj) continue;
        const attempt = toAttempt(c, humanize(inj.paths, r));
        const t0 = performance.now();
        const a = analyze(data, attempt);
        out.push({ char: c, expect: inj.expect, got: new Set(a.errors.map((e) => e.type)), ms: performance.now() - t0 });
      }
  return out;
}

function metrics(samples: Sample[]) {
  const rows = TYPES.map((t) => {
    const tp = samples.filter((s) => s.expect === t && s.got.has(t)).length;
    const fn = samples.filter((s) => s.expect === t && !s.got.has(t)).length;
    const fp = samples.filter((s) => s.expect !== t && s.got.has(t)).length;
    const p = tp + fp ? tp / (tp + fp) : 0, rcl = tp + fn ? tp / (tp + fn) : 0;
    return { type: t, n: tp + fn, precision: p, recall: rcl, f1: p + rcl ? (2 * p * rcl) / (p + rcl) : 0 };
  });
  const clean = samples.filter((s) => s.expect === "clean");
  const fpr = clean.filter((s) => s.got.size > 0).length / (clean.length || 1);
  const ms = samples.map((s) => s.ms).sort((a, b) => a - b);
  return { rows, fpr, p95: ms[Math.floor(ms.length * 0.95)], n: samples.length };
}

function confusionMatrix(samples: Sample[]) {
  const cols = [...TYPES, "none"] as const;
  const head = `| injected ↓ / detected → | ${cols.join(" | ")} |\n|---|${cols.map(() => "---").join("|")}|`;
  const body = (["clean", ...TYPES] as const).map((e) => {
    const sub = samples.filter((s) => s.expect === e);
    const cells = cols.map((c) =>
      c === "none" ? sub.filter((s) => s.got.size === 0).length : sub.filter((s) => s.got.has(c)).length,
    );
    return `| ${e} | ${cells.join(" | ")} |`;
  });
  return [head, ...body].join("\n");
}

const pct = (x: number) => (x * 100).toFixed(1) + "%";
function table(title: string, m: ReturnType<typeof metrics>) {
  return [
    `### ${title} (${m.n} attempts)`,
    "",
    "| Error type | n | Precision | Recall | F1 |",
    "|---|---|---|---|---|",
    ...m.rows.map((r) => `| ${r.type} | ${r.n} | ${pct(r.precision)} | ${pct(r.recall)} | ${r.f1.toFixed(3)} |`),
    "",
    `Clean-attempt false-positive rate: **${pct(m.fpr)}** · analysis p95: **${m.p95.toFixed(2)} ms**`,
    "",
  ].join("\n");
}

const scope = data.scope;
const tune = scope.filter((_, i) => i % 2 === 0);
const held = scope.filter((_, i) => i % 2 === 1);
const tuneS = run(tune, 1), heldS = run(held, 2);
const md = [
  "# Synthetic error-detection results",
  "",
  `Generated by \`npm run evaluate\` · ${VARIANTS} noisy variants per kanji × injector · ${new Date().toISOString().slice(0, 10)}`,
  "",
  table("Tuning half", metrics(tuneS)),
  table("Held-out half", metrics(heldS)),
  "### Confusion matrix (held-out)",
  "",
  confusionMatrix(heldS),
  "",
  realHandwriting(),
  "",
].join("\n");

mkdirSync("docs/evaluation", { recursive: true });
writeFileSync("docs/evaluation/synthetic-results.md", md);
console.log(md);

/** Accuracy on human-labelled real handwriting (tests/fixtures with a non-null `label`). */
function realHandwriting(): string {
  const root = "tests/fixtures";
  const files = existsSync(root)
    ? readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory())
        .flatMap((d) => readdirSync(join(root, d.name)).map((f) => join(root, d.name, f)))
    : [];
  const labelled = files
    .map((f) => JSON.parse(readFileSync(f, "utf8")))
    .filter((fx) => fx.label);
  if (!labelled.length)
    return "### Real handwriting\n\nNo labelled fixtures yet. Import exports with `scripts/import-fixtures.ts` and fill in each fixture's `label`.\n";
  const samples: Sample[] = labelled.map((fx) => {
    const a = analyze(data, { target: fx.target, strokes: fx.strokes, device: fx.device, size: fx.size });
    const want = new Set<ErrorType>(fx.label.errors);
    if (fx.label.bestMatch && fx.label.bestMatch !== fx.target) want.add("confusion");
    // One sample per labelled error (or "clean"), so per-type metrics work with multi-error attempts.
    return { char: fx.target, expect: want.size ? [...want][0] : "clean", got: new Set(a.errors.map((e) => e.type)), ms: 0, want } as Sample & { want: Set<ErrorType> };
  });
  const rows = TYPES.map((t) => {
    const tp = samples.filter((s) => (s as Sample & { want: Set<ErrorType> }).want.has(t) && s.got.has(t)).length;
    const fn = samples.filter((s) => (s as Sample & { want: Set<ErrorType> }).want.has(t) && !s.got.has(t)).length;
    const fp = samples.filter((s) => !(s as Sample & { want: Set<ErrorType> }).want.has(t) && s.got.has(t)).length;
    const p = tp + fp ? tp / (tp + fp) : 0, r = tp + fn ? tp / (tp + fn) : 0;
    return `| ${t} | ${tp + fn} | ${pct(p)} | ${pct(r)} | ${p + r ? ((2 * p * r) / (p + r)).toFixed(3) : "—"} |`;
  });
  const writers = new Set(labelled.map((fx) => fx.writer)).size;
  return [`### Real handwriting (${labelled.length} labelled attempts, ${writers} writer${writers > 1 ? "s" : ""})`, "",
    "| Error type | n | Precision | Recall | F1 |", "|---|---|---|---|---|", ...rows, ""].join("\n");
}
