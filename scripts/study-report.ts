/**
 * Learning-study report (implementation.md §7.5): compares the 'full' (error-aware feedback)
 * and 'control' groups from the live database.
 *
 *   npm run study:report [-- --since 2026-10-15]
 *
 * Writes docs/evaluation/study-report.md. Needs SUPABASE_ACCESS_TOKEN in .env.
 * Measures (per group, participants = distinct signed-in users with ≥1 attempt):
 *  - clean-attempt rate overall, in the first vs the last third of each learner's attempts (improvement)
 *  - review recall rate (final grade ≥ Good) — retention under spaced repetition
 *  - errors per attempt by type, and look-alike confusions
 *  - mean writing time / hesitation
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { sql } from "./db.ts";

const sinceArg = process.argv.indexOf("--since");
const since = sinceArg > 0 ? process.argv[sinceArg + 1] : "1970-01-01";
if (!/^\d{4}-\d{2}-\d{2}$/.test(since)) throw new Error("--since must be YYYY-MM-DD");

type Row = Record<string, string | number | null>;
const base = `from public.attempts a where a.study_group is not null and a.client_created_at >= '${since}'`;

const overview = await sql<Row>(`
  select study_group as "group", count(distinct user_id) as participants, count(*) as attempts,
    round(avg((cardinality(errors) = 0)::int) * 100, 1) as clean_pct,
    round(avg(stroke_count), 1) as strokes_avg,
    round(avg(duration_ms) / 1000.0, 2) as secs_avg,
    round(avg(hesitation_ms) / 1000.0, 2) as hesitation_secs_avg
  ${base} group by 1 order by 1`);

// Improvement: clean rate in each learner's first vs last third of attempts.
const improvement = await sql<Row>(`
  with r as (
    select study_group, user_id, (cardinality(errors) = 0)::int as clean,
      ntile(3) over (partition by user_id order by client_created_at) as third
    ${base}
  )
  select study_group as "group",
    round(avg(clean) filter (where third = 1) * 100, 1) as first_third_clean_pct,
    round(avg(clean) filter (where third = 3) * 100, 1) as last_third_clean_pct,
    round((avg(clean) filter (where third = 3) - avg(clean) filter (where third = 1)) * 100, 1) as change_pts
  from r group by 1 order by 1`);

const recall = await sql<Row>(`
  select study_group as "group", count(*) as graded_reviews,
    round(avg((final_rating >= 3)::int) * 100, 1) as recalled_pct,
    round(avg((auto_rating = final_rating)::int) filter (where auto_rating is not null) * 100, 1) as auto_matches_final_pct
  ${base} and mode = 'review' and final_rating is not null group by 1 order by 1`);

const errorTypes = await sql<Row>(`
  select study_group as "group", e as error_type, round(count(*)::numeric / max(n.total), 3) as per_attempt
  from public.attempts a cross join lateral unnest(a.errors) e
  join (select study_group g, count(*) total ${base} group by 1) n on n.g = a.study_group
  where a.study_group is not null and a.client_created_at >= '${since}'
  group by 1, 2 order by 1, 3 desc`);

const perUser = await sql<Row>(`
  select study_group as "group", left(user_id::text, 8) as participant, count(*) as attempts,
    count(distinct kanji) as kanji, round(avg((cardinality(errors) = 0)::int) * 100, 1) as clean_pct,
    min(client_created_at)::date as first_day, max(client_created_at)::date as last_day
  ${base} group by 1, 2 order by 1, 3 desc`);

const table = (rows: Row[]) => {
  if (!rows.length) return "_No data yet._\n";
  const cols = Object.keys(rows[0]);
  return [`| ${cols.join(" | ")} |`, `|${cols.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${cols.map((c) => r[c] ?? "—").join(" | ")} |`)].join("\n") + "\n";
};

const md = `# Learning study report

Generated by \`npm run study:report\` on ${new Date().toISOString().slice(0, 10)} · attempts since ${since}.
Groups: **full** = error-aware feedback + recommendations + auto-graded reviews; **control** = correct/incorrect only + self-graded reviews.

> Descriptive statistics only. With small groups, report effect sizes and confidence intervals (or a Mann–Whitney U test on per-participant values) in the write-up; don't rely on raw percentages alone.

## Overview
${table(overview)}
## Improvement within learners (first vs last third of each learner's attempts)
${table(improvement)}
## Review recall (spaced repetition)
${table(recall)}
## Errors per attempt by type
${table(errorTypes)}
## Participants
${table(perUser)}`;

mkdirSync("docs/evaluation", { recursive: true });
writeFileSync("docs/evaluation/study-report.md", md);
console.log(md);
