/**
 * Robustness analysis: error-detection quality as handwriting noise increases.
 *   npm run robustness          → docs/evaluation/robustness.md
 * Noise level 1× = the default used in evaluate.ts (±15% scale, ±5° rotation, ±0.05 shift,
 * 0.006 jitter); every component is multiplied by the level. Held-out kanji only.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { analyze } from "../src/core/analyze.ts";
import { DEFAULT_NOISE, humanize, INJECT, rng, toAttempt } from "../src/core/synth/index.ts";
import type { ErrorType, KanjiData } from "../src/core/types.ts";

const data: KanjiData = JSON.parse(readFileSync("public/data/kanji.json", "utf8"));
const held = data.scope.filter((_, i) => i % 2 === 1);
const TYPES: ErrorType[] = ["order", "direction", "count", "proportion", "position", "confusion"];
const LEVELS = [0.5, 1, 1.5, 2, 3, 4];
const VARIANTS = Number(process.env.VARIANTS ?? 8);

type Row = { level: number; f1: Record<string, number>; macro: number; fpr: number };
const rows: Row[] = [];
for (const level of LEVELS) {
  const noise = {
    jitter: DEFAULT_NOISE.jitter * level, scale: DEFAULT_NOISE.scale * level,
    rotate: DEFAULT_NOISE.rotate * level, shift: DEFAULT_NOISE.shift * level,
  };
  const r = rng(1234);
  const samples: { expect: string; got: Set<ErrorType> }[] = [];
  for (const c of held)
    for (const inject of Object.values(INJECT))
      for (let v = 0; v < VARIANTS; v++) {
        const inj = inject(data, c, r);
        if (!inj) continue;
        const a = analyze(data, toAttempt(c, humanize(inj.paths, r, noise)));
        samples.push({ expect: inj.expect, got: new Set(a.errors.map((e) => e.type)) });
      }
  const f1: Record<string, number> = {};
  for (const t of TYPES) {
    const tp = samples.filter((s) => s.expect === t && s.got.has(t)).length;
    const fn = samples.filter((s) => s.expect === t && !s.got.has(t)).length;
    const fp = samples.filter((s) => s.expect !== t && s.got.has(t)).length;
    const p = tp + fp ? tp / (tp + fp) : 0, rc = tp + fn ? tp / (tp + fn) : 0;
    f1[t] = p + rc ? (2 * p * rc) / (p + rc) : 0;
  }
  const clean = samples.filter((s) => s.expect === "clean");
  rows.push({
    level, f1,
    macro: TYPES.reduce((s, t) => s + f1[t], 0) / TYPES.length,
    fpr: clean.filter((s) => s.got.size > 0).length / clean.length,
  });
  process.stdout.write(`${level}× `);
}

const desc = (l: number) =>
  `±${Math.round(DEFAULT_NOISE.scale * l * 100)}% scale, ±${(DEFAULT_NOISE.rotate * l).toFixed(1)}° rot, ±${(DEFAULT_NOISE.shift * l).toFixed(3)} shift`;
const md = [
  "# Robustness to handwriting noise",
  "",
  `Generated by \`npm run robustness\` · held-out kanji (${held.length}) · ${VARIANTS} variants per kanji × injector per level.`,
  "Noise 1× is the level used for the main results (evaluate.ts). Higher levels simulate sloppier writing.",
  "",
  `| Noise | Applied | ${TYPES.join(" | ")} | Macro F1 | False positives on clean |`,
  `|---|---|${TYPES.map(() => "---").join("|")}|---|---|`,
  ...rows.map((r) => `| ${r.level}× | ${desc(r.level)} | ${TYPES.map((t) => r.f1[t].toFixed(3)).join(" | ")} | **${r.macro.toFixed(3)}** | ${(r.fpr * 100).toFixed(1)}% |`),
  "",
].join("\n");
mkdirSync("docs/evaluation", { recursive: true });
writeFileSync("docs/evaluation/robustness.md", md);
console.log("\n" + md);
